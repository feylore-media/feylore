/**
 * Generates shelf-icon-registry.ts from SHELF_ICON_SOLAR_SLUGS.
 * Run: node scripts/generate-shelf-icon-registry.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { SHELF_ICON_IDS, SHELF_ICON_SOLAR_SLUGS } from "../src/shared/shelf-icons.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "../src/web/components/icons/shelf-icon-registry.ts");

function toPascal(slug) {
  return slug
    .split("-")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function importName(id, slug, variant) {
  const base = toPascal(slug);
  const idPascal = toPascal(id);
  const suffix = variant === "outline" ? "OutlineIcon" : "DuotoneIcon";
  return `Shelf_${idPascal}_${base}_${suffix}`;
}

const slugs = [...new Set(Object.values(SHELF_ICON_SOLAR_SLUGS))];

const outlineImports = slugs
  .map((slug) => {
    const name = toPascal(slug) + "OutlineIcon";
    return `import { ${name} as ${importName("_", slug, "outline").replace("Shelf__", "Solar_")} } from "@solar-icons/react/outline/${slug}";`;
  })
  .join("\n");

// Fix import aliases - use cleaner approach
const outlineLines = [];
const duotoneLines = [];
const slugToOutline = new Map();
const slugToDuotone = new Map();

for (const slug of slugs) {
  const pascal = toPascal(slug);
  const outlineVar = `${pascal}Outline`;
  const duotoneVar = `${pascal}Duotone`;
  slugToOutline.set(slug, outlineVar);
  slugToDuotone.set(slug, duotoneVar);
  outlineLines.push(
    `import { ${pascal}Icon as ${outlineVar} } from "@solar-icons/react/outline/${slug}";`,
  );
  duotoneLines.push(
    `import { ${pascal}Icon as ${duotoneVar} } from "@solar-icons/react/line-duotone/${slug}";`,
  );
}

const entries = SHELF_ICON_IDS.map((id) => {
  const slug = SHELF_ICON_SOLAR_SLUGS[id];
  const outline = slugToOutline.get(slug);
  const duotone = slugToDuotone.get(slug);
  const key = id.includes("-") ? `"${id}"` : id;
  return `  ${key}: { outline: ${outline}, identity: ${duotone} },`;
});

const content = `/* eslint-disable -- generated by scripts/generate-shelf-icon-registry.mjs */
import type { Icon as SolarIconComponent } from "@solar-icons/react/lib/types";
import type { ShelfIconId } from "@shared/shelf-icons";
${outlineLines.join("\n")}
${duotoneLines.join("\n")}

type IconPair = {
  outline: SolarIconComponent;
  identity: SolarIconComponent;
};

export const SHELF_ICON_COMPONENTS: Record<ShelfIconId, IconPair> = {
${entries.join("\n")}
};
`;

writeFileSync(outPath, content, "utf8");
console.log(`Wrote ${SHELF_ICON_IDS.length} icons to ${outPath}`);
